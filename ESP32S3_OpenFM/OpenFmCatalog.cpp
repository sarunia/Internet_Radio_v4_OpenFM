int count() { return 200; }

const Entry& entry(int slot) {
  if (slot < 0 || slot >= count()) slot = 0;
  return entries[slot];
}

String knownId(int slot) {
  if (slot < 0 || slot >= count()) return "";
  const uint16_t id = entries[slot].fixedId;
  return id ? String("OFM") + String(id) : String("");
}

String resolveId(int slot) {
  // Katalog statyczny: nie wykonujemy zapytan HTTP do GETRADIO.
  // Zwracamy tylko identyfikatory potwierdzone w dostarczonym CSV.
  return knownId(slot);
}

